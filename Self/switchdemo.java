public class switchdemo
{
    public static void main(String arg[])
    {
        int x = 100;

        switch (x)
        {
            case 1:
                System.out.println("Value of x is 1");
                break;
            case 2:
                System.out.println("Value of x is 2"); 
                break;
            case 3:
                System.out.println("Value of x is 3");
                break;
            case 4:
                System.out.println("Value of x is 4");
                break;
            default:
                System.out.println("Value of x is not in the range of 1 to 4");
            

        }   
     }    
}
